# ----------------------------------------------------------------- secrets (.env)
def load_env() -> dict:
    env = {}
    f = DEP / ".env"
    if f.exists():
        for line in f.read_text().splitlines():
            if "=" in line and not line.startswith("#"):
                k, v = line.split("=", 1)
                env[k] = v
    return env


env = load_env()
def secret(key: str) -> str:
    if key not in env:
        env[key] = secrets.token_urlsafe(24)
    return env[key]


