-- REED schema v1. IF NOT EXISTS lets Flyway adopt databases created by the
-- earlier Hibernate-managed backend (baseline-on-migrate, baseline-version 0).

-- ---------------------------------------------------------------- core REED tables
CREATE TABLE IF NOT EXISTS reed_asset_classification (
    asset_class             varchar(255) PRIMARY KEY,
    sensitivity             varchar(255),
    discoverability         varchar(255),
    default_policy_template varchar(255)
);

CREATE TABLE IF NOT EXISTS reed_policy_template (
    name        varchar(255) PRIMARY KEY,
    description varchar(512),
    odrl        varchar(4000)
);
-- Templates from before DCP used non-credential operands; let the seeder re-create them.
DELETE FROM reed_policy_template WHERE odrl LIKE '%reed:membership%';

CREATE TABLE IF NOT EXISTS reed_supply_chain_relation (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_bpn    varchar(255),
    child_bpn     varchar(255),
    relation_type varchar(255)
);

CREATE TABLE IF NOT EXISTS reed_access_request (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_bpn varchar(255),
    asset_id      varchar(255),
    asset_class   varchar(255),
    state         varchar(255),
    reason        varchar(512),
    created_at    timestamp(6) with time zone
);

CREATE TABLE IF NOT EXISTS reed_audit_event (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type varchar(255),
    actor_bpn  varchar(255),
    asset_id   varchar(255),
    detail     varchar(1024),
    at         timestamp(6) with time zone
);
-- Hibernate used to add enum CHECK constraints; new event types (MATCH, ASSIST) must be allowed.
ALTER TABLE reed_audit_event DROP CONSTRAINT IF EXISTS reed_audit_event_event_type_check;
CREATE INDEX IF NOT EXISTS reed_audit_event_at ON reed_audit_event (at DESC);

-- ---------------------------------------------------------------- directory + assets
CREATE TABLE reed_participant (
    bpn            varchar(255) PRIMARY KEY,
    name           varchar(255) NOT NULL,
    short_name     varchar(255),
    role           varchar(255) NOT NULL,
    consortium     boolean NOT NULL,
    country        varchar(255),
    city           varchar(255),
    vat_id         varchar(255),
    lat            double precision NOT NULL,
    lon            double precision NOT NULL,
    port_access    boolean NOT NULL,
    rail_access    boolean NOT NULL,
    sectors        jsonb,
    connector_name varchar(255) UNIQUE,
    dsp_url        varchar(255),
    management_url varchar(255),
    did            varchar(255),
    attestations   jsonb,
    capability     jsonb
);

CREATE TABLE reed_asset (
    asset_id        varchar(255) PRIMARY KEY,
    asset_class     varchar(255) NOT NULL,
    owner_bpn       varchar(255) NOT NULL REFERENCES reed_participant (bpn),
    title           varchar(255),
    description     varchar(1024),
    sensitivity     varchar(255),
    discoverability varchar(255),
    policy_template varchar(255),
    payload         jsonb
);
CREATE INDEX reed_asset_owner ON reed_asset (owner_bpn);

-- ---------------------------------------------------------------- matchmaking
CREATE TABLE reed_rfq (
    id                 varchar(255) PRIMARY KEY,
    buyer_bpn          varchar(255) NOT NULL REFERENCES reed_participant (bpn),
    title              varchar(255) NOT NULL,
    story              varchar(2048),
    sector             varchar(255),
    part_family        varchar(255),
    material           varchar(255),
    dims_mm            jsonb,
    mass_kg            double precision NOT NULL,
    tol_mm             double precision,
    quantity           integer NOT NULL,
    due_date           date,
    delivery_lat       double precision,
    delivery_lon       double precision,
    required_processes jsonb,
    required_certs     jsonb,
    partner_processes  jsonb,
    state              varchar(255),
    created_at         timestamp(6) with time zone
);

CREATE TABLE reed_match (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfq_id          varchar(255) NOT NULL,
    buyer_bpn       varchar(255) NOT NULL,
    supplier_bpn    varchar(255) NOT NULL REFERENCES reed_participant (bpn),
    score           double precision NOT NULL,
    breakdown       jsonb,
    state           varchar(255),
    detail_asset_id varchar(255),
    agreement_id    varchar(255),
    note            varchar(1024),
    on_time         boolean,
    quality_ok      boolean,
    updated_at      timestamp(6) with time zone,
    UNIQUE (rfq_id, supplier_bpn)
);
CREATE INDEX reed_match_supplier ON reed_match (supplier_bpn);

-- ---------------------------------------------------------------- credential attestation views
-- Read by the Issuer Service ("database" attestations, one row per holder DID) to
-- issue the verifiable credentials the EDC connectors check during negotiation.
-- The REED registry stays the single source of truth for who is attested what.
CREATE VIEW vc_membership AS
SELECT p.did AS holder_id, p.bpn, p.role, 'active' AS membership, p.name AS organisation, p.country
FROM reed_participant p
WHERE p.did IS NOT NULL AND p.consortium;

CREATE VIEW vc_certification AS
SELECT p.did AS holder_id, p.bpn,
       ',' || coalesce((SELECT string_agg(c, ',' ORDER BY c) FROM jsonb_array_elements_text(p.attestations) c), '') || ',' AS certifications
FROM reed_participant p
WHERE p.did IS NOT NULL AND p.consortium;

CREATE VIEW vc_supplier_relation AS
SELECT p.did AS holder_id, p.bpn,
       ',' || coalesce((SELECT string_agg(DISTINCT CASE WHEN r.parent_bpn = p.bpn THEN r.child_bpn ELSE r.parent_bpn END, ',')
                        FROM reed_supply_chain_relation r
                        WHERE (r.parent_bpn = p.bpn OR r.child_bpn = p.bpn) AND r.relation_type IN ('SUPPLIES', 'OWNS')), '') || ',' AS partners,
       ',' || coalesce((SELECT string_agg(DISTINCT CASE WHEN r.parent_bpn = p.bpn THEN r.child_bpn ELSE r.parent_bpn END, ',')
                        FROM reed_supply_chain_relation r
                        WHERE (r.parent_bpn = p.bpn OR r.child_bpn = p.bpn) AND r.relation_type = 'PROJECT_MEMBER'), '') || ',' AS projects
FROM reed_participant p
WHERE p.did IS NOT NULL AND p.consortium;
