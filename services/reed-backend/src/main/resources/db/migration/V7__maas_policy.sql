-- Manufacturing-as-a-Service with policy enforcement: onboarding attributes, capability offerings with a
-- compound ODRL policy, service RFQs, contracts carrying their effective policy (ODRL + generated Rego)
-- and the log of every Open Policy Agent decision.

-- ---------------------------------------------------------------- consortium management
ALTER TABLE reed_participant
    ADD COLUMN membership_status  varchar(16) NOT NULL DEFAULT 'ACTIVE',   -- PENDING | ACTIVE | SUSPENDED
    ADD COLUMN verified           boolean NOT NULL DEFAULT false,
    ADD COLUMN industry           varchar(64),
    ADD COLUMN competitor_classes jsonb NOT NULL DEFAULT '[]';
-- `consortium` stays (the credential views read it) and always equals membership_status = 'ACTIVE'.
UPDATE reed_participant SET membership_status = 'PENDING' WHERE NOT consortium;
UPDATE reed_participant SET verified = true WHERE consortium;

-- an offering's policy is a template of its own and may be longer than the hand-written ones
ALTER TABLE reed_policy_template ALTER COLUMN odrl TYPE text;

-- ---------------------------------------------------------------- capability catalogue
CREATE TABLE reed_offering (
    id                 varchar(64) PRIMARY KEY,
    provider_bpn       varchar(255) NOT NULL REFERENCES reed_participant (bpn),
    name               varchar(255) NOT NULL,
    capability         varchar(64) NOT NULL,
    resource_kind      varchar(32) NOT NULL,   -- SERVICE | DATASET | API | AVAILABILITY | CAPACITY | PARAMETERS | DIGITAL_TWIN
    resource           varchar(255),
    description        varchar(1024),
    keywords           jsonb NOT NULL DEFAULT '[]',
    capacity_per_month integer,
    asset_id           varchar(255) REFERENCES reed_asset (asset_id),
    policy_template    varchar(255) NOT NULL REFERENCES reed_policy_template (name),
    published          boolean NOT NULL DEFAULT false,
    created_at         timestamp(6) with time zone NOT NULL,
    published_at       timestamp(6) with time zone
);
CREATE INDEX reed_offering_provider ON reed_offering (provider_bpn);

-- ---------------------------------------------------------------- service RFQs (capability set: matched against offerings)
ALTER TABLE reed_rfq
    ADD COLUMN capability        varchar(64),
    ADD COLUMN keywords          jsonb,
    ADD COLUMN required_capacity integer,
    ADD COLUMN preferred_region  varchar(16),
    ADD COLUMN start_date        date,
    ADD COLUMN end_date          date,
    ADD COLUMN purpose           varchar(64);

-- ---------------------------------------------------------------- contracts
CREATE TABLE reed_contract (
    id           varchar(64) PRIMARY KEY,
    rfq_id       varchar(255),
    offering_id  varchar(64) NOT NULL REFERENCES reed_offering (id),
    provider_bpn varchar(255) NOT NULL REFERENCES reed_participant (bpn),
    consumer_bpn varchar(255) NOT NULL REFERENCES reed_participant (bpn),
    asset_id     varchar(255),
    start_date   date NOT NULL,
    expiry_date  date NOT NULL,
    purpose      varchar(64) NOT NULL,
    odrl         text NOT NULL,              -- the effective policy (ODRL Agreement)
    rego         text NOT NULL,              -- what REED generated from it
    policy_id    varchar(128) NOT NULL,
    status       varchar(16) NOT NULL,       -- DRAFT | NEGOTIATING | AGREED | ACTIVE | EXPIRED | TERMINATED
    agreement_id varchar(128),               -- the EDC contract agreement behind it
    deployed_to  varchar(255),               -- the provider's policy decision point
    created_at   timestamp(6) with time zone NOT NULL,
    accepted_at  timestamp(6) with time zone,
    agreed_at    timestamp(6) with time zone,
    deployed_at  timestamp(6) with time zone,
    updated_at   timestamp(6) with time zone NOT NULL
);
CREATE INDEX reed_contract_parties ON reed_contract (consumer_bpn, provider_bpn);

-- ---------------------------------------------------------------- policy decision log
CREATE TABLE reed_policy_decision (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at            timestamp(6) with time zone NOT NULL,
    stage         varchar(16) NOT NULL,      -- MATCH | RUNTIME | SIMULATED
    requester_bpn varchar(255),
    provider_bpn  varchar(255),
    contract_id   varchar(64),
    offering_id   varchar(64),
    rfq_id        varchar(255),
    asset_id      varchar(255),
    action        varchar(32),
    purpose       varchar(64),
    decision      varchar(8) NOT NULL,       -- ALLOW | DENY
    policy_id     varchar(128),
    decided_by    varchar(255),              -- which Open Policy Agent answered
    conditions    jsonb,
    failed        jsonb,
    explanation   varchar(2048)
);
CREATE INDEX reed_policy_decision_at ON reed_policy_decision (at DESC);
