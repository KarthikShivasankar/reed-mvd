-- Shop floor: sensor readings (time series, written over MQTT) and operator observations.

-- sensor_key = <connector>/<machine>/<sensor>; a reading is idempotent, so replays and backfills are harmless.
CREATE TABLE reed_sensor_reading (
    sensor_key varchar(200)             NOT NULL,
    ts         timestamp(6) with time zone NOT NULL,
    value      double precision         NOT NULL,
    PRIMARY KEY (sensor_key, ts)
);

CREATE TABLE reed_observation (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant varchar(255),
    machine_id  varchar(255),
    category    varchar(255),
    severity    varchar(255),
    text        varchar(2000),
    summary     varchar(500),
    source      varchar(255),
    author      varchar(255),
    created_at  timestamp(6) with time zone
);
CREATE INDEX reed_observation_participant_at ON reed_observation (participant, created_at DESC);
