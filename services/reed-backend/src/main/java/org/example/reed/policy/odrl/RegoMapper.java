package org.example.reed.policy.odrl;

import java.util.function.Function;

/**
 * {@link PolicyNode} -> one Rego module for Open Policy Agent. Every constraint becomes a named
 * boolean rule that defaults to false (a missing input attribute fails, never passes) and one entry
 * in {@code conditions}, so OPA's answer lists each condition with its outcome; ALLOW/DENY is
 * derived from that list and nothing else.
 *
 * <p>The module answers two questions:
 * <ul>
 *   <li>{@code eligibility} - do the policy's own conditions hold? (matchmaking time)</li>
 *   <li>{@code decision} - the same, and an active REED contract covers the request (runtime).</li>
 * </ul>
 */
public final class RegoMapper {

    private RegoMapper() {
    }

    /** The Rego package of a policy: {@code reed.policy.<name>}; {@link #name} makes any id a valid identifier. */
    public static String name(String policyId) {
        return "p_" + policyId.toLowerCase(java.util.Locale.ROOT).replaceAll("[^a-z0-9_]", "_");
    }

    /**
     * @param contractId the contract the module belongs to, or null for an offering's policy (then
     *                   {@code decision} needs any active contract in the input - there is none when a
     *                   consumer got an agreement at the connector without a REED contract)
     * @param label      BPN -> company name, for the condition texts
     */
    public static String toRego(String policyId, PolicyNode policy, String contractId, Function<String, String> label) {
        var rules = new StringBuilder();
        var conditions = new StringBuilder();
        int i = 0;
        for (var atom : enforced(policy)) {
            var id = "c" + (++i);
            rule(rules, id, atom.kind().rego(atom));
            condition(conditions, id, atom.kind().name(), atom.kind().label(atom, label));
        }
        rule(rules, "c0", contractId == null
                ? java.util.List.of("input.contract.status == \"ACTIVE\"")
                : java.util.List.of("input.contract.id == " + quote(contractId), "input.contract.status == \"ACTIVE\""));

        return "# Generated by REED from an ODRL policy. Do not edit: change the ODRL policy instead.\n"
                + "package reed.policy." + name(policyId) + "\n\n"
                + "import rego.v1\n\n"
                + rules
                + "conditions := [\n" + conditions + "]\n\n"
                + "contract_conditions := [\n"
                + "    {\"id\": \"c0\", \"kind\": \"CONTRACT\", \"label\": \"An active REED contract covers this request\", \"pass\": c0},\n"
                + "]\n\n"
                + "eligibility := result(conditions)\n\n"
                + "decision := result(array.concat(conditions, contract_conditions))\n\n"
                + "result(cs) := {\n"
                + "    \"decision\": verdict([c | some c in cs; not c.pass]),\n"
                + "    \"policy\": " + quote(policyId) + ",\n"
                + "    \"conditions\": cs,\n"
                + "    \"failed\": [c | some c in cs; not c.pass],\n"
                + "}\n\n"
                + "verdict(failed) := \"ALLOW\" if count(failed) == 0\n\n"
                + "verdict(failed) := \"DENY\" if count(failed) > 0\n";
    }

    /**
     * The conditions a module checks: the policy's own, and always an active consortium membership. A
     * provider may leave membership out of its policy; nobody outside the consortium gets data for that.
     */
    public static java.util.List<PolicyNode.Atom> enforced(PolicyNode policy) {
        var atoms = new java.util.ArrayList<>(PolicyNode.atoms(policy));
        if (atoms.stream().noneMatch(a -> a.kind() == ConstraintKind.MEMBERSHIP)) {
            atoms.add(new PolicyNode.Atom(ConstraintKind.MEMBERSHIP, "eq", java.util.List.of("active")));
        }
        return atoms;
    }

    private static void rule(StringBuilder out, String id, java.util.List<String> statements) {
        out.append("default ").append(id).append(" := false\n\n").append(id).append(" if {\n");
        statements.forEach(s -> out.append("    ").append(s).append('\n'));
        out.append("}\n\n");
    }

    private static void condition(StringBuilder out, String id, String kind, String label) {
        out.append("    {\"id\": \"").append(id).append("\", \"kind\": \"").append(kind).append("\", \"label\": ")
                .append(quote(label)).append(", \"pass\": ").append(id).append("},\n");
    }

    /** A Rego (JSON) string literal. Values come from policies people type: never concatenate them unquoted. */
    static String quote(String s) {
        var b = new StringBuilder("\"");
        for (char ch : s.toCharArray()) {
            switch (ch) {
                case '"' -> b.append("\\\"");
                case '\\' -> b.append("\\\\");
                default -> {
                    if (ch < 0x20) {
                        b.append(String.format("\\u%04x", (int) ch));
                    } else {
                        b.append(ch);
                    }
                }
            }
        }
        return b.append('"').toString();
    }
}
