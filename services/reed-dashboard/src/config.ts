/** A participant's EDC connector (generated from deployment/roster.json). */
export interface ConnectorRef {
  name: string;
  bpn: string;
  company: string;
  short: string;
  /** EDC participant id - the DID under DCP. */
  participantId: string;
  /** DSP address, resolved connector-to-connector inside Docker (service name). */
  dspUrl: string;
  /** Public data plane the browser pulls EDR-protected payloads from. */
  publicUrl: string;
}

export interface AppConfig {
  reedBackendUrl: string;
  keycloak: { url: string; realm: string; clientId: string };
  identityMode: string;
  connectors: ConnectorRef[];
}

const FALLBACK: AppConfig = {
  reedBackendUrl: "http://localhost:8081",
  keycloak: { url: "http://localhost:8180", realm: "reed", clientId: "reed-dashboard" },
  identityMode: "dcp",
  connectors: [],
};

/** Loaded at runtime (bind-mounted, generated by tools/gen_topology.py) so endpoints change without a rebuild. */
export async function loadConfig(): Promise<AppConfig> {
  try {
    const res = await fetch("/config.json", { cache: "no-store" });
    if (!res.ok) return FALLBACK;
    return { ...FALLBACK, ...(await res.json()) };
  } catch {
    return FALLBACK;
  }
}
